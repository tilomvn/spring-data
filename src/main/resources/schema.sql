DROP TABLE STRING_ID_MINION IF EXISTS;
DROP TABLE REF_MINION IF EXISTS;

CREATE TABLE REF_MINION(
   ID VARCHAR(50) PRIMARY KEY,
   REF_NAME VARCHAR(100)
);

CREATE TABLE STRING_ID_MINION(
   ID VARCHAR(50) PRIMARY KEY,
   NAME VARCHAR(100),
   REF_MINION_ID VARCHAR(50),
   CONSTRAINT FK_REF_MINION FOREIGN KEY (REF_MINION_ID) REFERENCES REF_MINION(ID)
);
